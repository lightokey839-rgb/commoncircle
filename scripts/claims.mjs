import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";

const evidencePath = process.argv[2] ?? "evidence/evidence.json";
const readmePath = "README.md";
const outputPath = "EVIDENCE.md";
const startMarker = "<!-- COMMONCIRCLE_TRACK_TABLE_START -->";
const endMarker = "<!-- COMMONCIRCLE_TRACK_TABLE_END -->";
const allowedKinds = new Set(["tx", "view", "test"]);

const document = JSON.parse(await readFile(evidencePath, "utf8"));
if (document.schema_version !== "A9") {
  console.error(`unsupported evidence schema: expected A9, got ${document.schema_version ?? "missing"}`);
  process.exitCode = 1;
}
const claims = Array.isArray(document.claims) ? document.claims : [];
const failures = [];

function validateShape(claim, index) {
  const required = ["id", "track", "feature", "network", "kind", "reference", "expected"];
  for (const field of required) {
    if (!(field in claim) || claim[field] === "" || claim[field] == null) {
      failures.push(`${index + 1}: missing ${field}`);
    }
  }
  if (claim.kind && !allowedKinds.has(claim.kind)) {
    failures.push(`${claim.id ?? index + 1}: invalid kind ${claim.kind}`);
  }
}

claims.forEach(validateShape);

function containsExpected(actual, expected) {
  if (expected === null || typeof expected !== "object") return actual === expected;
  if (Array.isArray(expected)) return Array.isArray(actual) && expected.every((item, index) => containsExpected(actual[index], item));
  if (actual === null || typeof actual !== "object") return false;
  return Object.entries(expected).every(([key, value]) => containsExpected(actual[key], value));
}

async function readJson(path) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch {
    return null;
  }
}

// Gate 0 intentionally has no claim rows. For populated A9 rows, the harness
// requires a committed JSON snapshot/report and compares the expected subset;
// it never treats a free-form README sentence as proof.
async function verifyClaim(claim) {
  const pathKey = claim.kind === "test" ? "report" : "snapshot";
  const path = typeof claim.reference === "object" ? claim.reference[pathKey] : null;
  if (!path) return { status: "FAIL", reason: `${claim.kind} reference must name ${pathKey}` };
  const actual = await readJson(path);
  if (actual === null) return { status: "FAIL", reason: `invalid or missing JSON evidence: ${path}` };
  if (!containsExpected(actual, claim.expected)) return { status: "FAIL", reason: `expected value does not match ${path}` };
  return { status: "PASS", reason: `expected value matches ${path}` };
}

const results = [];
for (const [index, claim] of claims.entries()) {
  const invalid = failures.some((failure) => failure.startsWith(`${index + 1}:`) || failure.startsWith(`${claim.id}:`));
  results.push({ claim, ...(invalid ? { status: "FAIL", reason: "invalid claim shape" } : await verifyClaim(claim)) });
}

const tracks = new Map();
for (const result of results) {
  const track = result.claim.track;
  const current = tracks.get(track) ?? { feature: result.claim.feature, statuses: [] };
  current.statuses.push(result.status);
  tracks.set(track, current);
}

const trackLines = [
  startMarker,
  "<!-- Generated by `npm run claims`; do not edit this table manually. -->",
  "| Track | Feature | Evidence status |",
  "| --- | --- | --- |",
];
if (tracks.size === 0) {
  trackLines.push("| _No verified tracks yet_ | — | UNVERIFIED |");
} else {
  for (const [track, value] of tracks) {
    const status = value.statuses.every((item) => item === "PASS") ? "PASS" : "DROPPED";
    trackLines.push(`| ${track} | ${value.feature} | ${status} |`);
  }
}
trackLines.push(endMarker);

let readme = await readFile(readmePath, "utf8");
const start = readme.indexOf(startMarker);
const end = readme.indexOf(endMarker);
if (start >= 0 && end >= start) {
  readme = `${readme.slice(0, start)}${trackLines.join("\n")}${readme.slice(end + endMarker.length)}`;
} else {
  readme = `${readme.trimEnd()}\n\n${trackLines.join("\n")}\n`;
}
await writeFile(readmePath, readme);

const evidenceLines = [
  "# CommonCircle evidence",
  "",
  `Generated by \`npm run claims\` from \`${evidencePath}\`.`,
  "",
  "| ID | Track | Kind | Status | Reference | Result |",
  "| --- | --- | --- | --- | --- | --- |",
];
if (results.length === 0) {
  evidenceLines.push("| — | — | — | UNVERIFIED | — | No claim rows recorded. |");
} else {
  for (const result of results) {
    const reference = typeof result.claim.reference === "string"
      ? result.claim.reference
      : JSON.stringify(result.claim.reference);
    evidenceLines.push(`| ${result.claim.id} | ${result.claim.track} | ${result.claim.kind} | ${result.status} | ${reference} | ${result.reason} |`);
  }
}
await writeFile(outputPath, `${evidenceLines.join("\n")}\n`);

console.log(evidenceLines.join("\n"));
if (failures.length > 0 || results.some((result) => result.status !== "PASS")) {
  if (failures.length > 0) console.error(failures.join("\n"));
  process.exitCode = 1;
}
